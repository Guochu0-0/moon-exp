function [p1,p2,conf] = traditional270_himo(opt, sar, config)
% HIMO A_HIMO_demo.m, with B0 image loading and the final geometry omitted.
[~,scale1] = Deal_Extreme(opt,64,512,0);
[~,scale2] = Deal_Extreme(sar,64,512,0);
[~,img1] = Preproscessing(opt,scale1,[]);
[~,img2] = Preproscessing(sar,scale2,[]);
assert(scale1 == 1 && scale2 == 1 && isequal(size(img1), size(opt)) ...
       && isequal(size(img2), size(sar)), 'HIMO auxiliary preprocessing changed patch geometry.');

[mag1,angle1,response1] = Build_Himo_Pyramid(img1,config.octaves,config.layers, ...
    config.resize,config.sigma,config.patch_size,config.location_bins, ...
    config.intensity_difference,config.detector);
[mag2,angle2,response2] = Build_Himo_Pyramid(img2,config.octaves,config.layers, ...
    config.resize,config.sigma,config.patch_size,config.location_bins, ...
    config.intensity_difference,config.detector);
points1 = Detect_Himo_Keypoint(img1,response1,config.detector_border,config.detector_threshold, ...
    config.suppression_radius,config.keypoint_limit,config.octaves,config.resize,config.detector);
points2 = Detect_Himo_Keypoint(img2,response2,config.detector_border,config.detector_threshold, ...
    config.suppression_radius,config.keypoint_limit,config.octaves,config.resize,config.detector);
if isempty(points1) || isempty(points2)
    p1 = zeros(0,2); p2 = zeros(0,2); conf = zeros(0,1);
    return
end
[cor1,cor2,distance] = Multiscale_Strategy(points1,points2,mag1,mag2,angle1,angle2, ...
    config.patch_size,config.location_bins,config.orientation_bins,config.resize, ...
    config.internal_threshold,config.internal_repetitions,config.internal_transform, ...
    config.rotation,config.scale,config.parallel);
p1 = cor1(:,1:2);
p2 = cor2(:,1:2);
conf = 1 ./ (1 + distance);
end
